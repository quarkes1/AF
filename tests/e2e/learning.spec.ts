import {test,expect,_electron as electron} from '@playwright/test'
import {createServer,type ViteDevServer} from 'vite'
import {resolve} from 'node:path'
import {mkdir} from 'node:fs/promises'

async function launch(review=false){
  const old=process.env.VITE_LEARNING_REVIEW
  let server:ViteDevServer|undefined
  if(review){process.env.VITE_LEARNING_REVIEW='1';server=await createServer({configFile:resolve('config/vite.preview.ts'),server:{port:0,strictPort:false},logLevel:'silent'});await server.listen()}
  const app=await electron.launch({args:[resolve('build/compiled/main/index.js'),'--mute-audio'],env:{...process.env,AF_TEST_MODE:'1',...(server?{ELECTRON_RENDERER_URL:server.resolvedUrls!.local[0]}:{})}})
  const page=await app.firstWindow(),errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.addInitScript(()=>{
    const calls:string[]=[];Object.defineProperty(window,'__learningAudioCalls',{value:calls})
    const play=HTMLMediaElement.prototype.play;HTMLMediaElement.prototype.play=function(){calls.push(this.src);return play.call(this)}
  })
  await page.evaluate(()=>localStorage.setItem('af.frontend-preview.preferences.v1',JSON.stringify({muted:true,reducedMotion:false})))
  await page.reload();await page.keyboard.press('Escape');await expect(page.getByTestId('title-screen')).toBeVisible()
  await page.keyboard.press('x');await expect(page.getByTestId('home')).not.toHaveAttribute('inert','')
  return {page,errors,close:async()=>{await app.close();await server?.close();if(old===undefined)delete process.env.VITE_LEARNING_REVIEW;else process.env.VITE_LEARNING_REVIEW=old}}
}

